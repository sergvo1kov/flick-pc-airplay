'use strict';
// Runs the bundled UxPlay (AirPlay receiver core) as a child process.
//
// Options go through a UTF-8 startup file ("-rc uxplay.rc") instead of the
// command line: on Windows argv is ANSI, which would mangle a Cyrillic device
// name. All file names are relative to the runtime directory (the process cwd),
// so a non-ASCII Windows user name can't break UxPlay's fopen() either.

const { spawn, execFile } = require('child_process');
const EventEmitter = require('events');
const fs = require('fs');
const path = require('path');

const FILES = { rc: 'uxplay.rc', cover: 'cover.jpg', meta: 'meta.txt', dacp: 'dacp.txt', pid: 'engine.pid' };

function quote(v) {
  return `"${String(v).replace(/"/g, "'")}"`;
}

/** Build the UxPlay startup file from app settings. */
function buildRc(settings) {
  const lines = [
    '# generated by Flick AirPlay - do not edit, it is rewritten on every start',
    `n ${quote(settings.deviceName || 'Flick AirPlay')}`,
    'nh',
    `ca ${FILES.cover}`,
    `md ${FILES.meta}`,
    `dacp ${FILES.dacp}`,
  ];
  if (settings.video) {
    // d3d11videosink without options gets UxPlay's Alt+Enter full-screen toggle
    lines.push('vs d3d11videosink');
    lines.push('hls');               // YouTube app: video comes straight from YouTube (HTTPS HLS)
    if (settings.videoFullscreen) lines.push('fs');
  } else {
    lines.push('vs 0');
  }
  if (settings.taperVolume) lines.push('taper');
  if (settings.allowTakeover) lines.push('nohold');
  if (settings.audioSink && settings.audioSink !== 'auto') lines.push(`as ${settings.audioSink}`);
  return lines.join('\n') + '\n';
}

function engineEnv(engineDir, runtimeDir, baseEnv = process.env) {
  const bin = path.join(engineDir, 'bin');
  const plugins = path.join(engineDir, 'lib', 'gstreamer-1.0');
  const env = { ...baseEnv };
  // Windows env keys are case-insensitive; drop every PATH variant before setting ours.
  const oldPath = env.PATH || env.Path || '';
  for (const k of Object.keys(env)) if (k.toUpperCase() === 'PATH' || k.toUpperCase() === 'UXPLAYRC') delete env[k];
  return {
    ...env,
    PATH: `${bin}${path.delimiter}${oldPath}`,
    GST_PLUGIN_PATH_1_0: plugins,
    GST_PLUGIN_SYSTEM_PATH_1_0: plugins,
    GST_PLUGIN_SCANNER_1_0: path.join(engineDir, 'libexec', 'gstreamer-1.0', 'gst-plugin-scanner.exe'),
    GST_REGISTRY_1_0: path.join(runtimeDir, 'gst-registry.bin'),
    GIO_MODULE_DIR: path.join(engineDir, 'lib', 'gio', 'modules'),   // TLS for HTTPS (YouTube)
  };
}

/** Splits a stream into lines on \n and \r (UxPlay redraws progress with \r). */
class LineSplitter {
  constructor(onLine) { this.buf = ''; this.onLine = onLine; }
  push(chunk) {
    this.buf += chunk;
    const parts = this.buf.split(/\r\n|\r|\n/);
    this.buf = parts.pop();
    for (const p of parts) if (p.trim()) this.onLine(p);
    if (this.buf.length > 64 * 1024) this.buf = '';
  }
}

class Engine extends EventEmitter {
  constructor({ engineDir, runtimeDir, log = () => {} }) {
    super();
    this.engineDir = engineDir;
    this.runtimeDir = runtimeDir;
    this.log = log;
    this.proc = null;
    this.settings = null;
    this.stopping = false;
    this.crashes = [];
    this.restartTimer = null;
    this.pollTimer = null;
    this.lastFiles = {};
    this.state = 'stopped';
    this.lastError = '';
  }

  get exePath() { return path.join(this.engineDir, 'bin', 'uxplay.exe'); }
  file(name) { return path.join(this.runtimeDir, FILES[name]); }

  _setState(state, error = '') {
    this.state = state;
    if (error) this.lastError = error;
    this.emit('state', { state, error: this.lastError });
  }

  async start(settings) {
    this.settings = settings;
    this.stopping = false;
    fs.mkdirSync(this.runtimeDir, { recursive: true });
    await this._killOrphan();
    for (const f of ['cover', 'meta', 'dacp']) fs.rmSync(this.file(f), { force: true });
    fs.writeFileSync(this.file('rc'), buildRc(settings), 'utf8');
    this.lastFiles = {};

    if (!fs.existsSync(this.exePath)) {
      this._setState('error', `uxplay.exe not found: ${this.exePath}`);
      return;
    }
    this._setState('starting');
    const proc = spawn(this.exePath, ['-rc', FILES.rc], {
      cwd: this.runtimeDir,
      env: engineEnv(this.engineDir, this.runtimeDir),
      windowsHide: true,
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    this.proc = proc;
    fs.writeFileSync(this.file('pid'), String(proc.pid));
    const split = new LineSplitter((line) => {
      this.emit('line', line);
      if (this.state === 'starting' && /UxPlay .*server|Initialized|dnssd|raop/i.test(line)) this._setState('running');
      if (/\*\*\* ERROR/.test(line)) this.lastError = line.replace(/^\*\*\* ERROR:\s*/, '');
    });
    proc.stdout.setEncoding('utf8');
    proc.stderr.setEncoding('utf8');
    proc.stdout.on('data', (d) => split.push(d));
    proc.stderr.on('data', (d) => split.push(d));
    proc.on('error', (e) => this._setState('error', e.message));
    proc.on('exit', (code, signal) => this._onExit(proc, code, signal));
    // If nothing matched the "running" heuristics, consider it up after 3 s alive.
    setTimeout(() => { if (this.proc === proc && this.state === 'starting') this._setState('running'); }, 3000);
    this._startPolling();
  }

  _onExit(proc, code, signal) {
    if (this.proc !== proc) return;
    this.proc = null;
    this._stopPolling();
    fs.rmSync(this.file('pid'), { force: true });
    this.emit('files', { meta: null, cover: null, dacp: null });
    if (this.stopping) { this._setState('stopped'); return; }
    const now = Date.now();
    this.crashes = this.crashes.filter((t) => now - t < 60_000);
    this.crashes.push(now);
    this.log(`uxplay exited (code ${code}, signal ${signal})`);
    this.emit('crash', { code, count: this.crashes.length, settings: this.settings });
    if (this.crashes.length > 5) {
      this._setState('error', this.lastError || `AirPlay engine keeps crashing (exit code ${code})`);
      return;
    }
    this._setState('restarting', this.lastError);
    const delay = 1000 * this.crashes.length;
    this.restartTimer = setTimeout(() => this.start(this.settings), delay);
  }

  async stop() {
    this.stopping = true;
    clearTimeout(this.restartTimer);
    this._stopPolling();
    const proc = this.proc;
    if (!proc) { this._setState('stopped'); return; }
    await new Promise((resolve) => {
      const t = setTimeout(resolve, 3000);
      proc.once('exit', () => { clearTimeout(t); resolve(); });
      try { proc.kill(); } catch (_) { resolve(); }
    });
  }

  async restart(settings) {
    await this.stop();
    this.crashes = [];
    this.lastError = '';
    await this.start(settings || this.settings);
  }

  /** Kill a uxplay.exe left over from a previous crash of this app (it would hold the ports). */
  _killOrphan() {
    let pid;
    try { pid = Number(fs.readFileSync(this.file('pid'), 'utf8')); } catch (_) { return Promise.resolve(); }
    if (!pid || process.platform !== 'win32') return Promise.resolve();
    return new Promise((resolve) => {
      execFile('tasklist', ['/FI', `PID eq ${pid}`, '/FO', 'CSV', '/NH'], { windowsHide: true }, (err, out) => {
        if (!err && /uxplay\.exe/i.test(out)) {
          execFile('taskkill', ['/PID', String(pid), '/F'], { windowsHide: true }, () => resolve());
        } else resolve();
      });
    });
  }

  // ---- exported files -----------------------------------------------------

  _startPolling() {
    this._stopPolling();
    this.pollTimer = setInterval(() => this._poll(), 400);
  }

  _stopPolling() {
    clearInterval(this.pollTimer);
    this.pollTimer = null;
  }

  _poll() {
    const changes = {};
    for (const name of ['meta', 'cover', 'dacp']) {
      let st = null;
      try { st = fs.statSync(this.file(name)); } catch (_) { /* missing */ }
      const sig = st ? `${st.mtimeMs}:${st.size}` : 'none';
      if (this.lastFiles[name] === sig) continue;
      this.lastFiles[name] = sig;
      if (!st) { changes[name] = null; continue; }
      try {
        const buf = fs.readFileSync(this.file(name));
        changes[name] = name === 'cover' ? buf : buf.toString('utf8');
      } catch (_) {
        delete this.lastFiles[name]; // file is being rewritten: retry next poll
      }
    }
    if (Object.keys(changes).length) this.emit('files', changes);
  }

  /** IP of the connected client, from the engine's established TCP connections. */
  clientIp() {
    const P = require('./parsers');
    if (!this.proc || process.platform !== 'win32') return Promise.resolve(null);
    const pid = this.proc.pid;
    return new Promise((resolve) => {
      execFile('netstat', ['-ano', '-p', 'TCP'], { windowsHide: true, maxBuffer: 8 * 1024 * 1024 }, (err, out) => {
        if (err) return resolve(null);
        resolve(P.pickClientIp(P.parseNetstat(out, pid)));
      });
    });
  }
}

module.exports = { Engine, buildRc, engineEnv, LineSplitter, FILES };
