function pickLanguage(setting, systemLocale = 'en') {
  if (STRINGS[setting]) return setting;
  const l = String(systemLocale).toLowerCase();
  if (l.startsWith('uk')) return 'uk';
  if (l.startsWith('ru')) return 'ru';
  return 'en';
}

function format(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : ''));
}

function strings(lang) { return STRINGS[lang] || STRINGS.en; }

module.exports = { STRINGS, pickLanguage, format, strings };
